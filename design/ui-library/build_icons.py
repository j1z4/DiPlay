#!/usr/bin/env python3
"""Regenerate icons.js from the app's ic_dp_*.xml vector drawables.

Run from the repository root:  python3 design/ui-library/build_icons.py
"""
import glob
import json
import os
import xml.etree.ElementTree as ET

A = "{http://schemas.android.com/apk/res/android}"
HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, "..", "..", "common", "src", "main", "res", "drawable")
OUT = os.path.join(HERE, "icons.js")


def svg_paths(path):
    parts = []
    for p in ET.parse(path).getroot().iter("path"):
        d = p.get(A + "pathData")
        stroke = p.get(A + "strokeColor")
        fill = p.get(A + "fillColor") or ""
        rule = ' fill-rule="evenodd"' if p.get(A + "fillType") == "evenOdd" else ""
        if stroke and (not fill or "transparent" in fill):
            width = p.get(A + "strokeWidth", "2")
            parts.append(
                f'<path d="{d}" fill="none" stroke="currentColor" stroke-width="{width}" '
                'stroke-linecap="round" stroke-linejoin="round"/>'
            )
        else:
            parts.append(f'<path d="{d}" fill="currentColor"{rule}/>')
    return "".join(parts)


def main():
    icons = {
        os.path.basename(f)[len("ic_dp_"):-len(".xml")]: svg_paths(f)
        for f in sorted(glob.glob(os.path.join(SRC, "ic_dp_*.xml")))
    }
    with open(OUT, "w") as out:
        out.write("/* Generated by build_icons.py from common/src/main/res/drawable/ic_dp_*.xml. Do not edit. */\n")
        out.write("window.DP_ICONS = " + json.dumps(icons, indent=2) + ";\n")
    print(f"{len(icons)} icons -> {os.path.relpath(OUT)}")


if __name__ == "__main__":
    main()
