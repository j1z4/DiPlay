#!/usr/bin/env python3
"""Validate settings/catalog.json and write the copies the two previews read.

  design/ui-library/settings/catalog.js               (window.OPENPLAY_SETTINGS, for the web prototype)
  mobile/src/debug/assets/openplay_settings.json      (the Android debug preview)

Run from anywhere:  python3 design/ui-library/settings/build_catalog.py
"""
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, "..", "..", ".."))
SRC = os.path.join(HERE, "catalog.json")
WEB = os.path.join(HERE, "catalog.js")
APP = os.path.join(ROOT, "mobile", "src", "debug", "assets", "openplay_settings.json")

KINDS = {"toggle", "picker", "segment", "number", "slider", "text", "button", "link", "note", "info", "swatches"}


def rows(data):
    for cat in data["categories"]:
        for card in cat["cards"]:
            for row in card.get("rows", []):
                yield f'{cat["id"]} / {card.get("title")}', row
    for pid, page in data["pages"].items():
        for row in page["rows"]:
            yield f"page {pid}", row


def validate(data):
    errors = []
    defaults = {}
    for where, row in rows(data):
        kind = row.get("kind")
        if kind not in KINDS:
            errors.append(f"{where}: unknown kind {kind!r}")
        key = row.get("key")
        if key:
            if key in defaults and defaults[key] != row.get("default"):
                errors.append(f"{where}: {key} default {row.get('default')!r} differs from {defaults[key]!r}")
            defaults.setdefault(key, row.get("default"))
            if kind in ("picker", "segment") and row.get("default") not in row.get("options", []):
                errors.append(f"{where}: {key} default not among options")
    for where, row in rows(data):
        for dep in row.get("when", {}):
            if dep not in defaults:
                errors.append(f"{where}: 'when' refers to unknown key {dep!r}")
    return errors, defaults


def main():
    with open(SRC) as f:
        data = json.load(f)
    errors, defaults = validate(data)
    if errors:
        print("\n".join(errors))
        sys.exit(1)
    text = json.dumps(data, ensure_ascii=False, separators=(",", ":"))
    with open(WEB, "w") as out:
        out.write("/* Generated by build_catalog.py from catalog.json. Do not edit. */\n")
        out.write(f"window.OPENPLAY_SETTINGS = {text};\n")
    os.makedirs(os.path.dirname(APP), exist_ok=True)
    with open(APP, "w") as out:
        out.write(text)
    count = sum(1 for _ in rows(data))
    print(f"{len(data['categories'])} categories, {count} rows, {len(defaults)} settings -> catalog.js, openplay_settings.json")


if __name__ == "__main__":
    main()
